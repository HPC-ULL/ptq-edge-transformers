"""Programmatic generation of the LLM-branch experiment manifest (Phases 1-2).

3 models x 7 entries (1 baseline + 2 calibration_corpus + 2 calib_set_size +
2 block-scheme exception) = 21 entries. Phase 3 depends on Phase-2 results
and is generated by a separate module once those results exist.

Block-scheme exception ("block scheme" / quant_scheme): not a plain
2-level OFAT factor. The declared exception combines it with
calibration_corpus in two ways:
  - legacy + calibration_corpus=none        (single deviation from baseline)
  - legacy + calibration_corpus=wikitext2   (combined deviation, the exception)
A third combination, k_quant + calibration_corpus=wikitext2, would complete
the 2x2 grid, but it is identical in every config field to the
calibration_corpus OFAT variant already generated (same corpus, same
calib_set_size, quant_scheme already at its baseline value) -- generating it
again would just quantize the same artifact under a second run_id, so it is
intentionally skipped.
"""

from __future__ import annotations

from typing import Any, Dict, List

from .common import Factor, baseline_entry, build_run_id, ofat_variants, write_manifest

FAMILY = "llm"
BITWIDTH = "q4km"  # nominal 4-bit tier; block format is captured by quant_scheme, not bitwidth
REFERENCE_CALIB_SET_SIZE = 200
MODELS = ["tinyllama_1_1b", "qwen2_5_1_5b", "ministral_3_3b"]

BASELINE: Dict[str, Any] = {
    "calibration_corpus": "none",
    "calib_set_size": REFERENCE_CALIB_SET_SIZE,
    "quant_scheme": "k_quant",
    "bitwidth": BITWIDTH,
}

FACTORS = [
    Factor("calibration_corpus", ["none", "wikitext2", "domain_corpus"]),
    # calib_set_size only means anything once a corpus is in use, so every
    # level of this factor is generated with calibration_corpus fixed to
    # wikitext2 rather than the global baseline ("none").
    Factor(
        "calib_set_size",
        [REFERENCE_CALIB_SET_SIZE, 50, 1000],
        fixed={"calibration_corpus": "wikitext2"},
    ),
]

# (run_id level slug, field overrides) for the two non-duplicate block-scheme
# combinations -- see module docstring.
_BLOCK_SCHEME_COMBOS = [
    ("legacy_corpus_none", {"quant_scheme": "legacy", "calibration_corpus": "none"}),
    (
        "legacy_corpus_wikitext2",
        {
            "quant_scheme": "legacy",
            "calibration_corpus": "wikitext2",
            "calib_set_size": REFERENCE_CALIB_SET_SIZE,
        },
    ),
]


def _clear_inapplicable_calib_set_size(entry: Dict[str, Any]) -> Dict[str, Any]:
    """calib_set_size does not apply when there is no calibration corpus."""
    if entry["calibration_corpus"] == "none":
        entry["calib_set_size"] = None
    return entry


def _block_scheme_exception(model: str) -> List[Dict[str, Any]]:
    entries = []
    for level_slug, overrides in _BLOCK_SCHEME_COMBOS:
        entry = {
            "run_id": build_run_id(FAMILY, model, "phase2", "quant_scheme", level_slug, BITWIDTH),
            "model_family": FAMILY,
            "model_name": model,
            "phase": "phase2",
            "factor_varied": "quant_scheme",
            "factor_level": level_slug,
        }
        entry.update(BASELINE)
        entry.update(overrides)
        entries.append(_clear_inapplicable_calib_set_size(entry))
    return entries


def generate() -> List[Dict[str, Any]]:
    entries: List[Dict[str, Any]] = []
    for model in MODELS:
        entries.append(_clear_inapplicable_calib_set_size(baseline_entry(FAMILY, model, BITWIDTH, BASELINE)))
        entries.extend(
            _clear_inapplicable_calib_set_size(e)
            for e in ofat_variants(FAMILY, model, BITWIDTH, BASELINE, FACTORS)
        )
        entries.extend(_block_scheme_exception(model))
    return entries


def write() -> None:
    entries = generate()
    path = write_manifest(entries, "llm_experiment_manifest.yaml")
    print(f"Wrote {len(entries)} entries to {path}")
