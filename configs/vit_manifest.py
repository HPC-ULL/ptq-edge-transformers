"""Programmatic generation of the ViT-branch experiment manifest (Phases 1-2).

3 models x (1 baseline + 7 OFAT variants) = 24 entries. Phase 3 (optimal
combination vs. aggressive extreme) depends on Phase-2 results and is
generated by a separate module once those results exist.
"""

from __future__ import annotations

from typing import Any, Dict, List

from .common import Factor, baseline_entry, ofat_variants, write_manifest

FAMILY = "vit"
BITWIDTH = "int8"
MODELS = ["deit_tiny", "mobilevit", "efficientvit_b1"]

BASELINE: Dict[str, Any] = {
    "calibration_algorithm": "minmax",
    "granularity": "per_tensor",
    "symmetry": "symmetric",
    "calib_set_size": 128,
    "bitwidth": BITWIDTH,
}

# First level of each factor is the baseline level (skipped when generating
# Phase-2 variants); the rest are the OFAT variants for that factor.
FACTORS = [
    Factor("calibration_algorithm", ["minmax", "percentile", "mse", "entropy"]),
    Factor("granularity", ["per_tensor", "per_channel"]),
    Factor("symmetry", ["symmetric", "asymmetric"]),
    Factor("calib_set_size", [128, 32, 512]),
]


def generate() -> List[Dict[str, Any]]:
    entries: List[Dict[str, Any]] = []
    for model in MODELS:
        entries.append(baseline_entry(FAMILY, model, BITWIDTH, BASELINE))
        entries.extend(ofat_variants(FAMILY, model, BITWIDTH, BASELINE, FACTORS))
    return entries


def write() -> None:
    entries = generate()
    path = write_manifest(entries, "vit_experiment_manifest.yaml")
    print(f"Wrote {len(entries)} entries to {path}")
