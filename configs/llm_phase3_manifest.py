"""Programmatic generation of the LLM-branch Phase 3 manifest.

Mirrors configs/vit_phase3_manifest.py -- see its module docstring for the
general Phase 3 design (combined-vs-baseline at aggressive bitwidths, and
why configs/ importing from analysis/ + evaluation_offline/ here is a
deliberate exception to the rest of the project's dependency direction).

Aggressive Phase-3 bitwidths are Q3_K and Q2_K (vs. Phase 1-2's q4km);
"baseline" here is explicitly "sin imatrix" -- calibration_corpus="none",
the same deterministic global baseline used throughout Phase 1-2.

4 rows per model normally: baseline x {Q3_K,Q2_K} + combined x {Q3_K,Q2_K}.
If a model's combined config equals baseline in every factor (no Phase-2
candidate beat its margin for calibration_corpus, calib_set_size, OR
quant_scheme), the 2 "combined" rows are omitted as exact duplicates --
recorded in the written YAML's header, referencing
results/phase3_selection_report.txt. This is the shape exercised in
tests/test_phase3_manifest.py; it was the real outcome for salamandra_2b,
since retired from MODELS (its results live under results/appendix/).
"""

from __future__ import annotations

from typing import Any, Dict, List, Optional, Tuple

from .common import write_manifest_with_header
from . import llm_manifest

FAMILY = "llm"
AGGRESSIVE_BITWIDTHS = ["Q3_K", "Q2_K"]
COMPARISON_FIELDS = ["calibration_corpus", "calib_set_size", "quant_scheme"]


def _slug(value: Any) -> str:
    return str(value).strip().lower().replace(" ", "_")


def _run_id(model: str, kind: str, bitwidth: str) -> str:
    return f"{FAMILY}_{model}_phase3_{kind}_{_slug(bitwidth)}"


def _entry(model: str, kind: str, fields: Dict[str, Any], bitwidth: str) -> Dict[str, Any]:
    entry: Dict[str, Any] = {
        "run_id": _run_id(model, kind, bitwidth),
        "model_family": FAMILY,
        "model_name": model,
        "phase": "phase3",
        "factor_varied": "phase3_config",
        "factor_level": kind,
    }
    entry.update(fields)
    entry["bitwidth"] = bitwidth
    return entry


def generate(rows: Optional[List[Dict[str, Any]]] = None) -> Tuple[List[Dict[str, Any]], Dict[str, str]]:
    """Returns (entries, dedup_notes). `rows` lets callers (tests) inject
    synthetic llm_perplexity_offline.csv-shaped rows instead of reading the
    real file; defaults to reading it."""
    from analysis.phase3_selection.report import read_csv, select_llm_phase3, selected_config

    if rows is None:
        from evaluation_offline.llm_perplexity.paths import LLM_PERPLEXITY_RESULTS_CSV
        rows = read_csv(LLM_PERPLEXITY_RESULTS_CSV) if LLM_PERPLEXITY_RESULTS_CSV.exists() else []

    entries: List[Dict[str, Any]] = []
    dedup_notes: Dict[str, str] = {}

    raw_baseline = {k: llm_manifest.BASELINE[k] for k in COMPARISON_FIELDS}
    baseline_fields = llm_manifest._clear_inapplicable_calib_set_size(dict(raw_baseline))

    for model in llm_manifest.MODELS:
        decisions = select_llm_phase3(rows, model)
        combined_full = selected_config(decisions, normalize_config=llm_manifest._clear_inapplicable_calib_set_size)
        combined_fields = {k: combined_full[k] for k in COMPARISON_FIELDS}

        for bitwidth in AGGRESSIVE_BITWIDTHS:
            entries.append(_entry(model, "baseline", baseline_fields, bitwidth))

        if combined_fields == baseline_fields:
            dedup_notes[model] = (
                "combined config identical to baseline in every factor -- no Phase 2 "
                "candidate beat its margin for calibration_corpus, calib_set_size, or quant_scheme"
            )
        else:
            for bitwidth in AGGRESSIVE_BITWIDTHS:
                entries.append(_entry(model, "combined", combined_fields, bitwidth))

    return entries, dedup_notes


def write() -> None:
    entries, dedup_notes = generate()
    header_lines = [
        "Phase 3 manifest (llm_phase3_manifest.yaml) -- generated by configs/llm_phase3_manifest.py",
        "from analysis/phase3_selection/'s combined Phase 2 winners.",
        "Full per-factor selection detail: results/phase3_selection_report.txt",
    ]
    if dedup_notes:
        header_lines.append("")
        header_lines.append("Models whose 'combined' rows were omitted as exact duplicates of baseline:")
        for model, reason in dedup_notes.items():
            header_lines.append(f"  - {model}: {reason}")
    path = write_manifest_with_header(entries, "llm_phase3_manifest.yaml", header_lines)
    print(f"Wrote {len(entries)} entries to {path}")


if __name__ == "__main__":
    write()
