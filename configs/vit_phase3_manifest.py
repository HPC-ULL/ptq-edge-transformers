"""Programmatic generation of the ViT-branch Phase 3 manifest.

Phase 3 tests each model's Phase-2 combined "winner" configuration (see
analysis/phase3_selection/, technical_architecture.md Section 9.3)
against its own baseline, both at the two aggressive Phase-3 bitwidths
(INT6, INT4) -- so the ablation isolates "does the Phase 2 winning
combination help under aggressive quantization" from "how much does
aggressive quantization alone cost".

Unlike Phase 1-2's manifests (a static Factor/baseline OFAT expansion),
this one depends on Phase-2 RESULTS, not just config -- it's the one place
in this project where configs/ imports from analysis/ and
evaluation_offline/ rather than the other way around, per
technical_architecture.md Section 9.4 ("it is the only point of the
project where analysis/ feeds back into configs/").

4 rows per model normally: baseline x {int6,int4} + combined x {int6,int4}.
If a model's combined config is identical to baseline in every factor (no
Phase-2 candidate beat its margin for any factor -- happens when Phase 2
results show no clear winner anywhere), the 2 "combined" rows would be
exact duplicates of the 2 baseline rows and are omitted; only the 2
baseline rows are generated for that model. This is recorded in the
written YAML file's header comment (see write()), not just logged to
console -- referencing results/phase3_selection_report.txt for the full
per-factor detail behind the decision.
"""

from __future__ import annotations

from typing import Any, Dict, List, Optional, Tuple

from .common import write_manifest_with_header
from . import vit_manifest

FAMILY = "vit"
AGGRESSIVE_BITWIDTHS = ["int6", "int4"]
COMPARISON_FIELDS = ["calibration_algorithm", "granularity", "symmetry", "calib_set_size"]


def _slug(value: Any) -> str:
    return str(value).strip().lower().replace(" ", "_")


def _run_id(model: str, kind: str, bitwidth: str) -> str:
    return f"{FAMILY}_{model}_phase3_{kind}_{_slug(bitwidth)}"


def _entry(model: str, kind: str, fields: Dict[str, Any], bitwidth: str) -> Dict[str, Any]:
    entry: Dict[str, Any] = {
        "run_id": _run_id(model, kind, bitwidth),
        "model_family": FAMILY,
        "model_name": model,
        "phase": "phase3",
        "factor_varied": "phase3_config",
        "factor_level": kind,
    }
    entry.update(fields)
    entry["bitwidth"] = bitwidth
    return entry


def generate(rows: Optional[List[Dict[str, Any]]] = None) -> Tuple[List[Dict[str, Any]], Dict[str, str]]:
    """Returns (entries, dedup_notes). `rows` lets callers (tests) inject
    synthetic vit_accuracy_offline.csv-shaped rows instead of reading the
    real file; defaults to reading it."""
    from analysis.phase3_selection.report import read_csv, select_vit_phase3, selected_config

    if rows is None:
        from evaluation_offline.vit_accuracy.paths import VIT_ACCURACY_RESULTS_CSV
        rows = read_csv(VIT_ACCURACY_RESULTS_CSV) if VIT_ACCURACY_RESULTS_CSV.exists() else []

    entries: List[Dict[str, Any]] = []
    dedup_notes: Dict[str, str] = {}
    baseline_fields = {k: vit_manifest.BASELINE[k] for k in COMPARISON_FIELDS}

    for model in vit_manifest.MODELS:
        decisions = select_vit_phase3(rows, model)
        combined_full = selected_config(decisions)
        combined_fields = {k: combined_full[k] for k in COMPARISON_FIELDS}

        for bitwidth in AGGRESSIVE_BITWIDTHS:
            entries.append(_entry(model, "baseline", baseline_fields, bitwidth))

        if combined_fields == baseline_fields:
            dedup_notes[model] = (
                "combined config identical to baseline in every factor -- no Phase 2 "
                "candidate beat its margin for any factor"
            )
        else:
            for bitwidth in AGGRESSIVE_BITWIDTHS:
                entries.append(_entry(model, "combined", combined_fields, bitwidth))

    return entries, dedup_notes


def write() -> None:
    entries, dedup_notes = generate()
    header_lines = [
        "Phase 3 manifest (vit_phase3_manifest.yaml) -- generated by configs/vit_phase3_manifest.py",
        "from analysis/phase3_selection/'s combined Phase 2 winners.",
        "Full per-factor selection detail: results/phase3_selection_report.txt",
    ]
    if dedup_notes:
        header_lines.append("")
        header_lines.append("Models whose 'combined' rows were omitted as exact duplicates of baseline:")
        for model, reason in dedup_notes.items():
            header_lines.append(f"  - {model}: {reason}")
    path = write_manifest_with_header(entries, "vit_phase3_manifest.yaml", header_lines)
    print(f"Wrote {len(entries)} entries to {path}")


if __name__ == "__main__":
    write()
